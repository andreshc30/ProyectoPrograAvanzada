ALTER PROCEDURE dbo.SP_ASIGNAR_ROL_USUARIO
    @ID_USUARIO INT,
    @ID_ROL INT
AS
BEGIN
    SET NOCOUNT ON;

    DECLARE @ID_ESTADO_ACTIVO INT;

    SELECT @ID_ESTADO_ACTIVO = ID_ESTADO
    FROM dbo.FIDE_ESTADO_TB
    WHERE ESTADO = 'Activo';

    IF @ID_ESTADO_ACTIVO IS NULL
    BEGIN
        RAISERROR('No existe el estado Activo.', 16, 1);
        RETURN;
    END;

    IF NOT EXISTS (
        SELECT 1
        FROM dbo.FIDE_USUARIO_TB
        WHERE ID_USUARIO = @ID_USUARIO
          AND ID_ESTADO = @ID_ESTADO_ACTIVO
    )
    BEGIN
        RAISERROR('El usuario no existe o esta inactivo.', 16, 1);
        RETURN;
    END;

    IF NOT EXISTS (
        SELECT 1
        FROM dbo.FIDE_ROL_TB
        WHERE ID_ROL = @ID_ROL
          AND ID_ESTADO = @ID_ESTADO_ACTIVO
    )
    BEGIN
        RAISERROR('El rol no existe o esta inactivo.', 16, 1);
        RETURN;
    END;

    IF EXISTS (
        SELECT 1
        FROM dbo.FIDE_ROL_USUARIOS_TB
        WHERE ID_USUARIO = @ID_USUARIO
          AND ID_ROL = @ID_ROL
    )
    BEGIN
        UPDATE dbo.FIDE_ROL_USUARIOS_TB
        SET ID_ESTADO = @ID_ESTADO_ACTIVO
        WHERE ID_USUARIO = @ID_USUARIO
          AND ID_ROL = @ID_ROL;
    END
    ELSE
    BEGIN
        INSERT INTO dbo.FIDE_ROL_USUARIOS_TB
        (
            ID_USUARIO,
            ID_ROL,
            ID_ESTADO
        )
        VALUES
        (
            @ID_USUARIO,
            @ID_ROL,
            @ID_ESTADO_ACTIVO
        );
    END;
END;
GO

