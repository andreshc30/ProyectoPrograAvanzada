ALTER PROCEDURE dbo.SP_QUITAR_ROL_USUARIO
    @ID_USUARIO INT,
    @ID_ROL INT
AS
BEGIN
    SET NOCOUNT ON;

    DECLARE @ID_ACTIVO INT;
    DECLARE @ID_INACTIVO INT;

    SELECT @ID_ACTIVO = ID_ESTADO
    FROM dbo.FIDE_ESTADO_TB
    WHERE ESTADO = 'Activo';

    SELECT @ID_INACTIVO = ID_ESTADO
    FROM dbo.FIDE_ESTADO_TB
    WHERE ESTADO = 'Inactivo';

    IF @ID_INACTIVO IS NULL
    BEGIN
        RAISERROR('No existe el estado Inactivo.', 16, 1);
        RETURN;
    END;

    -- Protección básica del último administrador
    IF EXISTS (
        SELECT 1
        FROM dbo.FIDE_ROL_USUARIOS_TB RU
        INNER JOIN dbo.FIDE_ROL_TB R
            ON RU.ID_ROL = R.ID_ROL
        WHERE RU.ID_USUARIO = @ID_USUARIO
          AND RU.ID_ROL = @ID_ROL
          AND RU.ID_ESTADO = @ID_ACTIVO
          AND R.NOMBRE = 'Administrador'
    )
    AND (
        SELECT COUNT(DISTINCT RU.ID_USUARIO)
        FROM dbo.FIDE_ROL_USUARIOS_TB RU
        INNER JOIN dbo.FIDE_ROL_TB R
            ON RU.ID_ROL = R.ID_ROL
        INNER JOIN dbo.FIDE_USUARIO_TB U
            ON RU.ID_USUARIO = U.ID_USUARIO
        WHERE R.NOMBRE = 'Administrador'
          AND R.ID_ESTADO = @ID_ACTIVO
          AND RU.ID_ESTADO = @ID_ACTIVO
          AND U.ID_ESTADO = @ID_ACTIVO
    ) <= 1
    BEGIN
        RAISERROR('No se puede quitar el ultimo administrador.', 16, 1);
        RETURN;
    END;

    UPDATE dbo.FIDE_ROL_USUARIOS_TB
    SET ID_ESTADO = @ID_INACTIVO
    WHERE ID_USUARIO = @ID_USUARIO
      AND ID_ROL = @ID_ROL;
END;
GO

-- 9. DESACTIVAR USUARIO
IF OBJECT_ID('dbo.SP_DESACTIVAR_USUARIO', 'P') IS NULL
    EXEC('CREATE PROCEDURE dbo.SP_DESACTIVAR_USUARIO AS BEGIN SET NOCOUNT ON; END');
GO

ALTER PROCEDURE dbo.SP_DESACTIVAR_USUARIO
    @ID_USUARIO INT
AS
BEGIN
    SET NOCOUNT ON;

    DECLARE @ID_ACTIVO INT;
    DECLARE @ID_INACTIVO INT;

    SELECT @ID_ACTIVO = ID_ESTADO
    FROM dbo.FIDE_ESTADO_TB
    WHERE ESTADO = 'Activo';

    SELECT @ID_INACTIVO = ID_ESTADO
    FROM dbo.FIDE_ESTADO_TB
    WHERE ESTADO = 'Inactivo';

    IF @ID_INACTIVO IS NULL
    BEGIN
        RAISERROR('No existe el estado Inactivo.', 16, 1);
        RETURN;
    END;

    -- Protección básica del último administrador
    IF EXISTS (
        SELECT 1
        FROM dbo.FIDE_ROL_USUARIOS_TB RU
        INNER JOIN dbo.FIDE_ROL_TB R
            ON RU.ID_ROL = R.ID_ROL
        WHERE RU.ID_USUARIO = @ID_USUARIO
          AND RU.ID_ESTADO = @ID_ACTIVO
          AND R.NOMBRE = 'Administrador'
          AND R.ID_ESTADO = @ID_ACTIVO
    )
    AND (
        SELECT COUNT(DISTINCT RU.ID_USUARIO)
        FROM dbo.FIDE_ROL_USUARIOS_TB RU
        INNER JOIN dbo.FIDE_ROL_TB R
            ON RU.ID_ROL = R.ID_ROL
        INNER JOIN dbo.FIDE_USUARIO_TB U
            ON RU.ID_USUARIO = U.ID_USUARIO
        WHERE R.NOMBRE = 'Administrador'
          AND R.ID_ESTADO = @ID_ACTIVO
          AND RU.ID_ESTADO = @ID_ACTIVO
          AND U.ID_ESTADO = @ID_ACTIVO
    ) <= 1
    BEGIN
        RAISERROR('No se puede desactivar el ultimo administrador.', 16, 1);
        RETURN;
    END;

    UPDATE dbo.FIDE_USUARIO_TB
    SET ID_ESTADO = @ID_INACTIVO
    WHERE ID_USUARIO = @ID_USUARIO;
END;
GO

-- 10. LISTAR USUARIOS CON SUS ROLES
IF OBJECT_ID('dbo.SP_LISTAR_USUARIOS_ROLES', 'P') IS NULL
    EXEC('CREATE PROCEDURE dbo.SP_LISTAR_USUARIOS_ROLES AS BEGIN SET NOCOUNT ON; END');
GO

ALTER PROCEDURE dbo.SP_LISTAR_USUARIOS_ROLES
AS
BEGIN
    SET NOCOUNT ON;

    SELECT
        U.ID_USUARIO,
        U.CEDULA,
        U.NOMBRE,
        U.PRIMER_APELLIDO,
        U.CORREO,
        R.NOMBRE AS ROL,
        E.ESTADO
    FROM dbo.FIDE_USUARIO_TB U
    INNER JOIN dbo.FIDE_ESTADO_TB E
        ON U.ID_ESTADO = E.ID_ESTADO
    LEFT JOIN dbo.FIDE_ROL_USUARIOS_TB RU
        ON U.ID_USUARIO = RU.ID_USUARIO
        AND RU.ID_ESTADO = (
            SELECT ID_ESTADO
            FROM dbo.FIDE_ESTADO_TB
            WHERE ESTADO = 'Activo'
        )
    LEFT JOIN dbo.FIDE_ROL_TB R
        ON RU.ID_ROL = R.ID_ROL
        AND R.ID_ESTADO = (
            SELECT ID_ESTADO
            FROM dbo.FIDE_ESTADO_TB
            WHERE ESTADO = 'Activo'
        );
END;
GO


